// Canonical copy lives in locales/*.json. Bundle it for static and file:// use.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const languages = ['en', 'es'];
const locales = Object.fromEntries(languages.map(language => [language,
    JSON.parse(fs.readFileSync(path.join(root, 'locales', `${language}.json`), 'utf8'))
]));

function shape(value) {
    if (Array.isArray(value)) return 'array';
    if (value && typeof value === 'object') {
        return Object.fromEntries(Object.keys(value).sort().map(key => [key, shape(value[key])]));
    }
    return typeof value;
}

if (JSON.stringify(shape(locales.en)) !== JSON.stringify(shape(locales.es))) {
    throw new Error('English and Spanish content must have matching keys and value types.');
}

const output = '// Generated by node scripts/sync-locales.cjs. Edit locales/*.json instead.\n'
    + `const BreatheLocales = ${JSON.stringify(locales, null, 2)};\n`;
const destination = path.join(root, 'js', 'locales.generated.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== output) {
        throw new Error('Locale bundle is out of date. Run node scripts/sync-locales.cjs.');
    }
    console.log('Locale bundle is current; English and Spanish schemas match.');
} else {
    fs.writeFileSync(destination, output);
    console.log('Updated js/locales.generated.js.');
}
